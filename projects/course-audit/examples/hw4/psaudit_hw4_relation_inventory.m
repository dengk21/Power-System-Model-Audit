function inventory=psaudit_hw4_relation_inventory(hw4,model)
% Case-specific reviewed evidence: the TeX omits explicit total active balance.
texPath=fullfile(hw4,'HW4.tex'); sourcePath=fullfile(hw4,model);
reviewedTexHash='9d270e0c2e6aac6ebc3f7e4139720e71a0ed8d7e01a0b88dac9213a7eccbf812';
assert(strcmp(psaudit_hash_file(texPath),reviewedTexHash), ...
    'HW4 TeX differs from the semantically reviewed snapshot; repeat model review');
source=fileread(sourcePath); tex=fileread(texPath);
anchor='cons = [cons, sum(var.Pic) == zeros(1, num.T)];';
lines=regexp(source,'\r?\n','split'); active=[];
for k=1:numel(lines), if strcmp(strtrim(lines{k}),anchor), active(end+1)=k; end; end
assert(isscalar(active),'Reviewed balance implementation changed; re-review inventory');
% This locator is an integrity gate for one reviewed case, not a generic TeX completeness parser.
assert(contains(tex,'&P = G - D,') && ~contains(tex,'\sum_{n\in\mathcal N} P_{n,t} = 0'), ...
    'HW4 document changed: repeat semantic review before claiming a gap');
texLines=regexp(tex,'\r?\n','split'); section=find(strcmp(strtrim(texLines),'\subsection{约束条件}'));
assert(isscalar(section),'Reviewed insertion location changed');
supplement=strjoin({ ...
    '在无损直流经济调度模型中，每个时段还应满足全网有功功率平衡：', ...
    '\begin{align}', ...
    '  \sum_{n\in\mathcal N} P_{n,t} &= 0, && \forall t\in\mathcal T, \\', ...
    '  \sum_{i\in\mathcal G} g_{i,t} &= \sum_{n\in\mathcal N} D_{n,t}, && \forall t\in\mathcal T.', ...
    '\end{align}', ...
    '式中，$\mathcal N$、$\mathcal G$和$\mathcal T$分别为节点、运行机组和时段集合；', ...
    '$P_{n,t}$为节点净有功注入，$g_{i,t}$为机组总有功出力，$D_{n,t}$为节点有功负荷，功率单位均为$\mathrm{MW}$。', ...
    '同一节点的多台机组应分别计入求和。结合$P=G-D$及节点--机组映射，上述两式等价。'},newline);
inventory=struct('id','C_BAL_DOC','applicable',true,'textPresent',false,'codePresent',true, ...
    'textCorrect',NaN,'codeCorrect',1,'referenceVerified',true, ...
    'textLocation',sprintf('%s:%d (insert after the existing constraint align block)',texPath,section), ...
    'codeLocation',sprintf('%s:%d',sourcePath,active), ...
    'basis','HW4 is a fixed, lossless DC economic-dispatch model; all nodes and all 96 periods. Summing nodal power conservation gives zero total injection.', ...
    'evidence',['The active sum(Pic)=0 constraint and Pic=G-D implement total balance. The original TeX does not explicitly list this equality. Original TeX SHA-256: ' psaudit_hash_file(texPath)], ...
    'supplementLatex',supplement);
end
